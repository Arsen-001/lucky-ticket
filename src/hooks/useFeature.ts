'use client';

import { useGetMeQuery } from '@/api/me.api';

/**
 * Открыта ли фича этому игроку.
 *
 * Ответ считает сервер: у каждой фичи есть стадия — выключено / тестерам /
 * всем, — и `GET /me` присылает уже готовое да/нет. Список тестеров в клиент не
 * уезжает, а экран не решает свою видимость сам: решал бы — рано или поздно
 * разошёлся бы с сервером, который платит.
 *
 * `false`, пока ответа нет: лишнюю секунду без блока никто не заметит, а блок,
 * мигнувший у того, кому он не положен, — заметят все.
 *
 * ⚠️ Это ПОКАЗ, а не права. Фича, открытая тестерам, отбивает и запись тоже —
 * на сервере; прятать кнопку в одиночку никогда не достаточно.
 */
export function useFeature(key: string): boolean {
  const { data: me } = useGetMeQuery();
  return me?.features?.[key] === true;
}
