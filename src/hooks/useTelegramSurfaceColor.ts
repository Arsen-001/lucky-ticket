'use client';

import { useEffect } from 'react';
import { getTelegramWebApp } from '@/lib/telegram/telegram';

/** Цвет, который приложение держит на хроме телеграма по умолчанию. */
const APP_BG = '#1b1930';

/**
 * Перекрасить хром телеграма под экран, пока этот экран открыт.
 *
 * Телеграм рисует свою верхнюю полосу (и подложку под резинкой прокрутки) тем
 * цветом, который ему назвали через `setHeaderColor`. Приложение на старте
 * называет свой фон `#1b1930` — и это правда для всех экранов, кроме тех, у
 * кого есть СВОЙ мир. У дуэли он есть: её стол почти чёрный, и над ним
 * оставалась светлая полоса основного фона. Внутри игры её не видно в
 * полноэкранном режиме, но он даётся не всем клиентам, и там, где полоса
 * есть, шов между ней и столом виден первым.
 *
 * Возвращаем цвет приложения на выходе: экран уходит — его мир уходит с ним.
 */
export function useTelegramSurfaceColor(color: string): void {
  useEffect(() => {
    const tg = getTelegramWebApp();
    if (!tg) return;
    const paint = (next: string) => {
      try {
        tg.setHeaderColor?.(next);
        tg.setBackgroundColor?.(next);
      } catch {
        /* хром телеграма — по возможности, а не обязательство */
      }
    };
    paint(color);
    return () => paint(APP_BG);
  }, [color]);
}
