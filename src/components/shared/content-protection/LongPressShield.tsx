import { twMerge } from 'tailwind-merge';

export interface LongPressShieldProps {
  /** Чем накрыть, если по умолчанию накрывается не весь контейнер. */
  className?: string;
}

/**
 * Прозрачная накладка поверх картинки: под долгим нажатием клиент видит её, а
 * не `<img>`.
 *
 * Зачем, если `ContentProtectionProvider` уже гасит `contextmenu`. Затем, что
 * в Telegram на Android меню «Скачать · Открыть в браузере» рисует САМ КЛИЕНТ:
 * он вешает свой длинный тап на WebView и спрашивает у движка
 * `WebView.getHitTestResult()` — что лежит под пальцем. Событие в страницу при
 * этом не приходит, отменять нечего, и оба слоя защиты промахиваются мимо. Тип
 * `IMAGE_TYPE` там ставится по узлу, в который попал тап, поэтому лечится это
 * единственным способом: сделать так, чтобы верхним узлом была не картинка.
 *
 * Накладка — обычный `<span>` без фона: тапы она принимает (и они всплывают в
 * кнопку-родителя, как раньше), а картинкой не является. Родитель обязан быть
 * позиционированным, иначе `inset-0` растянется по чужому предку.
 *
 * 🪤 `pointer-events: none` НА САМОЙ НАКЛАДКЕ всё ломает: прозрачный для
 * нажатий узел выпадает из опроса, и попадание достаётся картинке под ним.
 * Не путать с тем же свойством на КАРТИНКЕ (`content-protection.css`): там
 * оно, наоборот, и есть защита — попадание уходит родителю, а он не
 * картинка. Это первый слой, накладка — второй, на случай если движок
 * опрашивает хит-тест флагом, который `pointer-events` игнорирует.
 *
 * Проверено e2e (`tikki-long-press.spec.ts`): верхний элемент над персонажем —
 * накладка, а не `<img>`. Живого замера в Telegram на Android нет; если меню
 * там всё-таки останется, следующий шаг — рисовать персонажа фоном
 * (`background-image`), тогда узла-картинки не существует вовсе.
 */
export function LongPressShield({ className }: LongPressShieldProps) {
  return (
    <span
      aria-hidden
      data-testid="long-press-shield"
      className={twMerge('absolute inset-0', className)}
    />
  );
}
